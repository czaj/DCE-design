% EXAMPLE_4_NGENE  Use an Ngene script, and compare with a design saved by Ngene.
%
% dce_ngene translates the script; dce_readngd reads an .ngd file, which holds
% a design together with the script that produced it.

addpath(fileparts(fileparts(mfilename('fullpath'))));

script = [ ...
    'design' newline ...
    ';alts = hotel1*, hotel2*' newline ...
    ';rows = 18' newline ...
    ';block = 3' newline ...
    ';eff = (mnl,d)' newline ...
    ';model:' newline ...
    'U(hotel1) = b1[-0.02] * price[120,180,240] + b2.dummy[0.4|0.7] * stars[3,5,1]' newline ...
    '          + b3.dummy[0.3|0.8] * meals[1,2,0] + b4.dummy[0.3] * pool[1,0] /' newline ...
    'U(hotel2) = b1 * price + b2.dummy * stars + b3.dummy * meals + b4.dummy * pool' newline ...
    '$'];

[spec, notes] = dce_ngene(script);            % notes: what the translation assumed
fprintf('%s\n', notes{:});
dce_check(spec);                              % base levels follow Ngene: the last level listed
result = dce_design(spec);

